import { chromium } from "playwright-core";
const stamp = Date.now();
const browser = await chromium.launch({ channel: "chrome", headless: true });
const p = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
await p.goto("http://localhost:3800/kayit");
await p.fill("input[name=businessName]", "Proba Hammadde");
await p.getByText("Restoran", { exact: true }).click();
await p.fill("input[name=name]", "Yiğit Proba");
await p.fill("input[name=email]", `proba-${stamp}@ornek.com`);
await p.fill("input[name=password]", "Cabukpos2026x");
await p.click('button[type="submit"]');
await p.waitForURL("**/yonetim**");
await p.goto("http://localhost:3800/yonetim/urunler");
await p.fill("input[name=name]", "Un");
await p.locator("label").filter({ hasText: "Hayır (hammadde" }).click();
await p.waitForTimeout(1200);
const kg = await p.locator("label").filter({ hasText: "Kg" }).count();
const hayirRenk = await p.locator("label").filter({ hasText: "Hayır (hammadde" }).first().evaluate((el) => el.className.includes("border-brand"));
console.log("Kg etiket:", kg, "| Hayır seçili mi:", hayirRenk);
await browser.close();
